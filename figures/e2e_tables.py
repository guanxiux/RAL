#!/usr/bin/env python3
"""tab:e2e-energy and tab:e2e-accuracy from logs/wise2_eval/ -> e2e_tables.csv, e2e_energy_table.tex,
e2e_accuracy_table.tex.

Same sources as e2e_stats.py (the loaders of experiments/wise2/report/eval_tables.py), so the numbers match
logs/wise2_eval/TABLES.md.  The two WildTrack cameras are one dataset: YOLOv8m energy is merged frame-weighted, accuracy
weighted by each camera's ground-truth boxes.

  * Energy: board energy per frame (mJ) on AGX Orin and Xavier NX.  YOLOv8m b4 is divided by the batch, so every column
    is per frame.  FireFlowNet: per-sequence energy blocks summed; DynConv: the run's energy block.
  * Accuracy: RTX 3080 (every platform runs the same masks).  FireFlowNet AEE weighted by valid frames; YOLOv8m b1
    AP50 and mAP50-95 on the annotated frames; DynConv PCKh.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "experiments/wise2/report"))
import eval_tables as et  # noqa: E402

PATHS = ("dense", "tile_skip", "gather_scatter", "wiseconv")
NAMES = {"dense": "Dense", "tile_skip": "Tile skipping", "gather_scatter": "Gather-scatter", "wiseconv": r"\sysname"}
GS = {"fireflownet": "gather_scatter", "dynconv_pose": "dynconv"}


def run(dev, cat, wl, dtype, path):
    backend = GS[wl] if path == "gather_scatter" else path
    mode = et.ours_run(dev, wl, dtype) if path == "wiseconv" else "static"
    return et.run_summary(dev, cat, wl, dtype, backend, mode)[0] if mode else None


# ------------------------------------------------------------------------------------------------------- energy

def yolo_energy(dev, task, dtype, batch):
    res = {}
    for path, v in et.yolo_rows(dev, task).get(dtype, {}).items():
        if path not in PATHS or not v["mj"]:
            continue
        frames = None
        for f in (f"{dtype}_static.json", f"{dtype}_updatable.json", f"{dtype}_baselines.json",
                  f"{dtype}_baselines_tile_skip.json", f"{dtype}_baselines_gather_scatter.json"):
            for d in (et.EV / dev / task / "e2e_energy", et.yolo_dir(dev, task)):
                j = et.load(d / f)
                E = (j or {}).get("backends", {}).get(path, {}).get("energy", {})
                if all(c in E for c in ("C3", "C6")):
                    frames = [E[c]["frames"] for c in ("C3", "C6")]
                    joules = [E[c]["energy_j"] for c in ("C3", "C6")]
        assert frames, (dev, task, dtype, path)
        res[path] = 1e3 * sum(joules) / sum(frames) / batch
    return res


def run_energy(dev, wl, dtype):
    res = {}
    for path in PATHS:
        s = run(dev, "latency", wl, dtype, path)
        if not s:
            continue
        blocks = [v["energy"] for v in s["sequences"].values() if "energy" in v] or ([s["energy"]] if "energy" in s else [])
        if blocks:
            res[path] = 1e3 * sum(b["energy_j"] for b in blocks) / sum(b["frames"] for b in blocks)
    return res


# ----------------------------------------------------------------------------------------------------- accuracy

def accuracy(dev, dtype):
    res = {}
    rows = et.yolo_rows(dev, "wildtrack640_yolov8m_select").get(dtype, {})
    d = et.yolo_dir(dev, "wildtrack640_yolov8m_select")
    for path in PATHS:
        a = {}
        s = run(dev, "accuracy", "fireflownet", dtype, path)
        if s:
            seq = s["sequences"].values()
            a["aee"] = sum(v["aee"] * v["valid_aee_frames"] for v in seq) / sum(v["valid_aee_frames"] for v in seq)
        s = run(dev, "accuracy", "dynconv_pose", dtype, path)
        if s:
            a["pckh"] = list(s["sequences"].values())[0]["pckh"]
        if path in rows:
            for f in (f"{dtype}_static.json", f"{dtype}_updatable.json", f"{dtype}_baselines.json"):
                j = et.load(d / f)
                A = (j or {}).get("backends", {}).get(path, {}).get("accuracy", {})
                if all(c in A for c in ("C3", "C6")):
                    n = [A[c]["pseudo_labels"] for c in ("C3", "C6")]
                    for k, key in (("ap50", "pseudo_ap50"), ("map", "pseudo_map50_95")):
                        a[k] = sum(A[c][key] * m for c, m in zip(("C3", "C6"), n)) / sum(n)
        if a:
            res[path] = a
    return res


# --------------------------------------------------------------------------------------------------------- tables

def energy_table(data):
    cols = [("fireflownet", "FireFlowNet"), ("yolov8m_b1", "YOLOv8m b1"), ("yolov8m_b4", "YOLOv8m b4"),
            ("dynconv", "DynConv")]
    L = [r"% Generated by figures/e2e_tables.py from logs/wise2_eval/.", r"\begin{table}[t]", r"\centering",
         r"\caption{Board energy per frame (mJ) on the Jetson platforms. Parentheses give each masked path's change"
         r" relative to Dense of the same precision; \sysname is in bold.}",
         r"\label{tab:e2e-energy}", r"\footnotesize", r"\setlength{\tabcolsep}{1.8pt}",
         r"\begin{tabular}{@{}c@{\hspace{4pt}}c@{\hspace{3pt}}l" + "r" * len(cols) + "@{}}", r"\toprule",
         # two header rows: the YOLOv8m columns split over both, the others centered across them
         r" & & & \multirow{2}{*}{FireFlowNet} & \multicolumn{1}{c}{YOLOv8m} & \multicolumn{1}{c}{YOLOv8m}"
         r" & \multirow{2}{*}{DynConv} \\",
         r" & & & & \multicolumn{1}{c}{b1} & \multicolumn{1}{c}{b4} & \\"]
    groups = [(p, d) for p in ("AGX Orin", "Xavier NX") for d in ("fp32", "fp16") if any(data.get((p, w, d)) for w, _ in cols)]
    fmt = lambda v: f"{v:.0f}" if v >= 100 else f"{v:.1f}"
    rot = lambda n, text: rf"\multirow{{{n}}}{{*}}{{\rotatebox[origin=c]{{90}}{{\scriptsize {text}}}}}"
    for gi, (plat, dtype) in enumerate(groups):
        paths = [p for p in PATHS if any(p in data.get((plat, w, dtype), {}) for w, _ in cols)]
        first = gi == 0 or groups[gi - 1][0] != plat
        span = sum(len([p for p in PATHS if any(p in data.get((q, w, d), {}) for w, _ in cols)])
                   for q, d in groups if q == plat)
        for k, path in enumerate(paths):
            cells = []
            for w, _ in cols:
                cell = data.get((plat, w, dtype), {})
                if path not in cell:
                    cells.append("--")
                    continue
                v = fmt(cell[path])
                s = rf"\textbf{{{v}}}" if path == "wiseconv" else v
                if path != "dense":
                    pct = f"{100 * (cell[path] / cell['dense'] - 1):+.1f}".replace("-", "$-$")
                    s += rf"\,{{\scriptsize({pct}\%)}}"
                cells.append(s)
            c1 = c2 = ""
            if k == 0:
                L.append(r"\midrule" if first else rf"\cmidrule{{2-{len(cols) + 3}}}")
                c2 = rot(len(paths), dtype.upper())
                if first:
                    c1 = rot(span, plat)
            L.append(f"{c1} & {c2} & {NAMES[path]} & " + " & ".join(cells) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (HERE / "e2e_energy_table.tex").write_text("\n".join(L) + "\n")


def accuracy_table(acc):
    cols = [("aee", r"AEE\,$\downarrow$", "FireFlowNet"), ("ap50", r"AP50\,$\uparrow$", "YOLOv8m"),
            ("map", r"mAP\,$\uparrow$", "YOLOv8m"), ("pckh", r"PCKh\,$\uparrow$", "DynConv")]
    L = [r"% Generated by figures/e2e_tables.py from logs/wise2_eval/.", r"\begin{table}[t]", r"\centering",
         r"\caption{Task accuracy on RTX~3080 (mAP over IoU 0.5--0.95). Dense runs the unmasked model; the three"
         r" masked paths consume the same layer masks.}",
         r"\label{tab:e2e-accuracy}", r"\footnotesize", r"\setlength{\tabcolsep}{3.2pt}",
         r"\begin{tabular}{@{}ll" + "c" * len(cols) + "@{}}", r"\toprule",
         r" & & FireFlowNet & \multicolumn{2}{c}{YOLOv8m b1} & DynConv \\",
         r"\cmidrule(lr){3-3}\cmidrule(lr){4-5}\cmidrule(lr){6-6}",
         " & & " + " & ".join(h for _, h, _ in cols) + r" \\", r"\midrule"]
    for gi, dtype in enumerate(("fp32", "fp16")):
        paths = [p for p in PATHS if p in acc[dtype]]
        for k, path in enumerate(paths):
            a = acc[dtype][path]
            cells = [f"{a[c]:.3f}" if c in ("aee", "ap50", "map") else f"{a[c]:.2f}" for c, _, _ in cols]
            head = rf"\multirow{{{len(paths)}}}{{*}}{{{dtype.upper()}}}" if k == 0 else ""
            L.append(f"{head} & {NAMES[path]} & " + " & ".join(cells) + r" \\")
        if gi == 0:
            L.append(r"\midrule")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (HERE / "e2e_accuracy_table.tex").write_text("\n".join(L) + "\n")


def main():
    energy, rows = {}, []
    for dev, plat in (("orin_sm87", "AGX Orin"), ("xavier_sm72", "Xavier NX")):
        for dtype in ("fp32", "fp16"):
            for key, val in (("fireflownet", run_energy(dev, "fireflownet", dtype)),
                             ("yolov8m_b1", yolo_energy(dev, "wildtrack640_yolov8m_select", dtype, 1)),
                             ("yolov8m_b4", yolo_energy(dev, "wildtrack640_yolov8m_b4_select", dtype, 4)),
                             ("dynconv", run_energy(dev, "dynconv_pose", dtype))):
                if "dense" in val:
                    energy[(plat, key, dtype)] = val
                    rows += [{"table": "energy", "platform": plat, "workload": key, "dtype": dtype, "path": p,
                              "metric": "mJ_per_frame", "value": f"{v:.4f}"} for p, v in val.items()]
    acc = {d: accuracy("rtx_3080_sm86", d) for d in ("fp32", "fp16")}
    for d, r in acc.items():
        rows += [{"table": "accuracy", "platform": "RTX 3080", "workload": "", "dtype": d, "path": p, "metric": m,
                  "value": f"{v:.5f}"} for p, a in r.items() for m, v in a.items()]
    with (HERE / "e2e_tables.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    energy_table(energy)
    accuracy_table(acc)
    print("-> e2e_tables.csv, e2e_energy_table.tex, e2e_accuracy_table.tex")


if __name__ == "__main__":
    main()
