"""Ego trajectories of the intro figure (teaser.tex), drawn on the road plane in perspective; writes teaser_traj.tex.
Road-plane points (X lateral, Z depth, both in camera heights) project to the figure (mm) with a pinhole camera fitted
to the frame's lane marking: x = CX + K X / Z, y = HOR - K / Z.  Each path is a ribbon of constant road-plane width, so
it narrows with depth; dashes, arrowheads and the marker disc are road-plane shapes projected the same way."""
import math

CX, HOR, K = 42.6, -16.5, 18.9           # vanishing point (mm) and focal scale, fitted to the dashed center line
LANE, TURN = 2.6, 3.0                     # right lane's center (the dashed line is at X = 1.3, the ego lane's left
                                          # edge at X = -1.4) and the depth a lane change takes
DISC = 0.13                               # road-plane radius of both marker discs

def proj(X, Z):
    return CX + K * X / Z, HOR - K / Z

def bezier(ctrl, n=80):
    out = []
    for i in range(n + 1):
        t = i / n
        k = len(ctrl) - 1
        pt = [0.0, 0.0]
        for j, (x, z) in enumerate(ctrl):
            b = math.comb(k, j) * (1 - t) ** (k - j) * t ** j
            pt[0] += b * x; pt[1] += b * z
        out.append(tuple(pt))
    return out

def lane_change(z0, z1, n=200, start=1.45):
    """Both systems share one turn profile: straight ahead, then X = LANE * smoothstep((Z - z0) / TURN), which
    reaches the right lane's center with the road's heading again; WISEConv starts it at once, Dense only after its
    perception finishes."""
    out = []
    for i in range(n + 1):
        z = z0 + (z1 - z0) * i / n
        t = min(max((z - start) / TURN, 0.0), 1.0)
        out.append((LANE * t * t * (3 - 2 * t), z))
    return out

def arclen(pts):
    L = [0.0]
    for a, b in zip(pts, pts[1:]):
        L.append(L[-1] + math.dist(a, b))
    return L

def ribbon(pts, w):
    """Road-plane polygon of half width w/2 around the polyline pts, projected."""
    left, right = [], []
    for i, (x, z) in enumerate(pts):
        a, b = pts[max(i - 1, 0)], pts[min(i + 1, len(pts) - 1)]
        dx, dz = b[0] - a[0], b[1] - a[1]; n = math.hypot(dx, dz)
        nx, nz = -dz / n * w / 2, dx / n * w / 2
        left.append(proj(x + nx, z + nz)); right.append(proj(x - nx, z - nz))
    return left + right[::-1]

def arrow(tip_base, direction, length, half):
    (x, z), (dx, dz) = tip_base, direction
    n = math.hypot(dx, dz); dx, dz = dx / n, dz / n
    return [proj(x - dz * half, z + dx * half), proj(x + dx * length, z + dz * length), proj(x + dz * half, z - dx * half)]

def disc(c, r, n=48):
    return [proj(c[0] + r * math.cos(2 * math.pi * i / n), c[1] + r * math.sin(2 * math.pi * i / n)) for i in range(n)]

def poly(pts, fill):
    return (f'\\filldraw[fill={fill}, draw=ink, line width=0.55pt, line join=round] '
            + ' -- '.join(f'({x:.3f},{y:.3f})' for x, y in pts) + ' -- cycle;')

def sub(pts, L, s0, s1):
    return [p for p, l in zip(pts, L) if s0 <= l <= s1]

lines = ['% generated by teaser_traj.py']
# Dense (dashed throughout): straight on from under the hood until its perception finishes (disc), then the late turn
dash = lane_change(1.1, 3.7, 800, start=2.55); L = arclen(dash)
g = 0.12                                  # dash gap; the dash length is fitted so that the last dash runs into the arrow
n = round((L[-1] + g) / (0.24 + g)); d = (L[-1] - (n - 1) * g) / n
for k in range(n):
    lines.append(poly(ribbon(sub(dash, L, k * (d + g), k * (d + g) + d), 0.15), 'baseline'))
end, prev = dash[-1], dash[-12]
lines.append(poly(arrow(end, (end[0] - prev[0], end[1] - prev[1]), 0.36, 0.2), 'baseline'))
lines.append(poly(disc((0, 2.42), DISC), 'baseline'))
# WISEConv: steers right early, then straightens in the next lane
path = lane_change(1.1, 4.6, 600, start=1.5)   # turns right from its start dot
lines.append(poly(ribbon(path, 0.13), 'wiseconv'))
end, prev = path[-1], path[-3]
lines.append(poly(arrow(end, (end[0] - prev[0], end[1] - prev[1]), 0.6, 0.3), "wiseconv"))
lines.append(poly(disc((0, 1.5), DISC), 'wiseconv'))   # the same road-plane size as Dense's
open('teaser_traj.tex', 'w').write('\n'.join(lines) + '\n')
for name, p in (('dense disc', (0, 2.42)), ('dense tip', dash[-1]), ('ours lane', (LANE, 1.5 + TURN)), ('ours tip', path[-1]), ("start", (0, 1.5))):
    print(name, [round(v, 2) for v in proj(*p)])
