#!/usr/bin/env python3
"""Generate the wise2 ablation table (YOLOv8m batch 1, RTX 3080, FP16) from ablation.csv (ablation_stats.py)."""

from __future__ import annotations

import csv
from pathlib import Path


HERE = Path(__file__).resolve().parent
SOURCE = HERE / "ablation.csv"
OUTPUT = HERE / "ablation_table.tex"
GROUPS = (("Constr.", ("no_reuse",)), ("Compute", ("shuffled", "readback", "full_grid")),
          ("Selection", ("dense_tile", "speedup_tile", "latency_tile", "kmax", "oracle")))


def cell(row: dict, field: str) -> str:
    value = row.get(field, "")
    return r"\textemdash{}" if value in (None, "") else f"{float(value):.2f}"


def make_table(rows: list[dict]) -> str:
    by = {row["variant"]: row for row in rows}
    expected = {k for _, keys in GROUPS for k in keys} | {"ours"}
    if set(by) != expected:
        raise ValueError("ablation CSV has unexpected rows")
    lines = [
        r"% Generated by figures/make_ablation_table.py from figures/ablation.csv.",
        r"\begin{table}[t]",
        r"  \centering",
        r"  \caption{Co-design ablation on YOLOv8m (b1, RTX~3080, FP16). Each variant replaces one mechanism"
        r" of \sysname. Construction, convolution, and total are ms per frame; the last column is latency"
        r" relative to \sysname, or $^{\dagger}$to the speedup-optimal configuration, which the variant modifies.}",
        r"  \Description{A table compares WISEConv design variants on RTX 3080 in FP16, grouped into",
        r"  construction-stage, compute-stage and tile-selection variants, reporting construction, convolution",
        r"  and total latency in milliseconds and the latency relative to the full design.}",
        r"  \label{tab:ablation}",
        r"  \footnotesize",
        r"  \setlength{\tabcolsep}{3.2pt}",
        r"  \begin{tabular}{@{}c@{\hspace{4pt}}lrrrc@{}}",
        r"    \toprule",
        r"    & Variant & Constr. & Conv. & Total & vs.\ \sysname \\",
    ]

    def emit(key: str, lead: str = "", bold: bool = False) -> None:
        row = by[key]
        label = rf"\textbf{{{row['variant_label']}}}" if bold else row["variant_label"]
        ratio = f"{float(row['ratio']):.2f}" + r"$\times$" + (r"\rlap{$^{\dagger}$}" if row["reference"] != "ours" else "")
        lines.append(f"    {lead} & {label} & {cell(row, 'construction_ms')} & {cell(row, 'convolution_ms')} & "
                     f"{cell(row, 'total_ms')} & {ratio} \\\\")

    for group, keys in GROUPS:
        lines.append(r"    \midrule")
        for i, key in enumerate(keys):
            lead = (rf"\multirow{{{len(keys)}}}{{*}}{{\rotatebox[origin=c]{{90}}{{\scriptsize {group}}}}}"
                    if i == 0 and len(keys) > 1 else (rf"\scriptsize {group}" if i == 0 else ""))
            emit(key, lead)
    lines.append(r"    \midrule")
    by["ours"]["variant_label"] = r"\sysname"
    emit("ours", bold=True)
    lines.extend([
        r"    \bottomrule",
        r"  \end{tabular}",
        r"\end{table}",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    with SOURCE.open(encoding="utf-8", newline="") as source:
        rows = list(csv.DictReader(source))
    temporary = OUTPUT.with_suffix(OUTPUT.suffix + ".tmp")
    temporary.write_text(make_table(rows), encoding="utf-8")
    temporary.replace(OUTPUT)
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
