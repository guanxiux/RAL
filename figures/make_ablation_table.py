#!/usr/bin/env python3
"""Generate the wise2 ablation table (YOLOv8m batch 1, FP16, RTX 3080 and AGX Orin) from ablation.csv (ablation_stats.py)."""

from __future__ import annotations

import csv
from pathlib import Path


HERE = Path(__file__).resolve().parent
SOURCE = HERE / "ablation.csv"
OUTPUT = HERE / "ablation_table.tex"
# (group, rows, row indices after which a thin rule separates sub-blocks): construction emits the worklist and its
# order and is rebuilt or reused; compute consumes it (launch, grid) under a selected tile configuration
GROUPS = (("Construction", ("no_reuse", "shuffled"), ()),
          ("Compute", ("readback", "full_grid", "dense_tile", "speedup_tile", "latency_tile", "kmax", "oracle"), ()))


# variant labels, one line each in the variant column
LABELS = {"no_reuse": "No reuse", "shuffled": "Shuffled order", "readback": r"Readback \& launch",
          "full_grid": "Full-layer grid", "dense_tile": r"Dense-tuned config.",
          "speedup_tile": r"Speedup-opt.\ config.", "latency_tile": r"Latency-opt.\ config.",
          "kmax": r"Cost-unaware $K_{\max}$", "oracle": "Zero-cost oracle", "ours": r"\sysname"}
DEVICES = (("rtx_3080_sm86", r"RTX~3080"), ("orin_sm87", r"AGX Orin"))


def cell(row: dict, field: str) -> str:
    value = row.get(field, "")
    return r"\textemdash{}" if value in (None, "") else f"{float(value):.2f}"


def make_table(rows: list[dict]) -> str:
    by = {(row["device"], row["variant"]): row for row in rows}
    expected = {k for _, keys, _ in GROUPS for k in keys} | {"ours"}
    for dev, _ in DEVICES:
        if {v for d, v in by if d == dev} != expected:
            raise ValueError(f"ablation CSV has unexpected rows for {dev}")
    lines = [
        r"% Generated by figures/make_ablation_table.py from figures/ablation.csv.",
        r"\begin{table}[t]",
        r"  \centering",
        r"  \caption{Co-design ablation on YOLOv8m (b1, FP16). Each variant replaces one mechanism of \sysname."
        r" Construction (Cons.), convolution (Conv.), and total are ms per frame; $\times$ is latency relative to"
        r" \sysname.}",
        r"  \Description{A table compares WISEConv design variants on RTX 3080 and AGX Orin in FP16, grouped into",
        r"  construction-stage and compute-stage variants, reporting construction, convolution",
        r"  and total latency in milliseconds and the latency relative to the full design on each GPU.}",
        r"  \label{tab:ablation}",
        r"  \footnotesize",
        r"  \setlength{\tabcolsep}{1.2pt}",
        r"  \begin{tabular*}{\columnwidth}{@{}>{\raggedright\arraybackslash}m{2.75cm}"
        r"@{\extracolsep{\fill}}rrrr@{\hspace{5pt}}rrrr@{}}",
        r"    \toprule",
        r"    & \multicolumn{4}{c}{" + DEVICES[0][1] + r"} & \multicolumn{4}{c}{" + DEVICES[1][1] + r"} \\",
        r"    \cmidrule(lr){2-5}\cmidrule(l){6-9}",
        r"    Variant & Cons. & Conv. & Total & $\times$ & Cons. & Conv. & Total & $\times$ \\",
    ]

    def emit(key: str, bold: bool = False) -> None:
        label = LABELS[key]
        label = rf"\textbf{{{label}}}" if bold else label
        cells = []
        for dev, _ in DEVICES:
            row = by[(dev, key)]
            ratio = f"{float(row['ratio']):.2f}"
            cells += [cell(row, "construction_ms"), cell(row, "convolution_ms"), cell(row, "total_ms"), ratio]
        lines.append(f"    {label} & " + " & ".join(cells) + r" \\")

    for group, keys, splits in GROUPS:
        lines.append(r"    \midrule")
        lines.append(rf"    \multicolumn{{9}}{{@{{}}l}}{{\textit{{{group}}}}} \\")
        for i, key in enumerate(keys):
            emit(key)
            if i in splits:
                lines.append(r"    \cmidrule(l){1-9}")
    lines.append(r"    \midrule")
    emit("ours", bold=True)
    lines.extend([
        r"    \bottomrule",
        r"  \end{tabular*}",
        r"\end{table}",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    with SOURCE.open(encoding="utf-8", newline="") as source:
        rows = list(csv.DictReader(source))
    temporary = OUTPUT.with_suffix(OUTPUT.suffix + ".tmp")
    temporary.write_text(make_table(rows), encoding="utf-8")
    temporary.replace(OUTPUT)
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
